package org.hanayori.liriope.api.border;

public enum BorderStyle {

    /**
     * Dust particles around the player. Works without a resource pack.
     */
    PARTICLE,

    /**
     * Packet-only TextDisplay panels that look like the vanilla world border with the Liriope resource pack,
     * and a translucent coloured wall without it.
     */
    TEXT_DISPLAY
}
